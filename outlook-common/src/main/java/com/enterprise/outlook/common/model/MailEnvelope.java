package com.enterprise.outlook.common.model;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/** Durable message envelope carried on Kafka topics (mail.outbound). */
public record MailEnvelope(
        UUID messageId,
        UUID tenantId,
        UUID senderMailboxId,
        UUID actingMailboxId,
        String senderEmail,
        String senderName,
        String onBehalfOfEmail,
        List<Recipient> to,
        List<Recipient> cc,
        List<Recipient> bcc,
        String subject,
        String bodyContent,
        String bodyType,
        String internetMessageId,
        String inReplyTo,
        UUID conversationId,
        short importance,
        List<AttachmentRef> attachments,
        Instant sentAt,
        Region region,
        boolean autoGenerated,
        String calendarIcs) {

    public record Recipient(String email, String name) {}

    public record AttachmentRef(UUID attachmentId, String fileName, String contentType, long sizeBytes,
                                String objectKey, boolean inline, String contentId) {}

    public List<Recipient> allRecipients() {
        var all = new ArrayList<Recipient>();
        if (to != null) all.addAll(to);
        if (cc != null) all.addAll(cc);
        if (bcc != null) all.addAll(bcc);
        return all;
    }
}
